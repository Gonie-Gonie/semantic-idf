func TestEnergyPathRealSQLDriverLinksIndependentFramesAndAllContexts(t *testing.T) {
	frames, model, checks, bundle := epathSQLDriverLinksFixture(t)
	before, _ := json.Marshal(frames)
	for _, check := range checks.Rows {
		if err := epathCheckSQLModelDriverLink(bundle, check); err != nil {
			t.Fatalf("%s: %v", check.Want.Key, err)
		}
	}
	if len(checks.Rows) != 2*13*2*3*2 { // two scopes,13periods,2services,2categories+incoming,2ends
		t.Fatalf("incomplete endpoint roster: %d", len(checks.Rows))
	}
	wall := epathSQLDriverAnnualWallCheck(t, checks)
	if math.Abs(wall.Quantity.Value-172.8) > 1e-10 || wall.DriverLink.Load.Value != 216 || !reflect.DeepEqual(wall.DriverLink.RequiredDriverSources, []int{12, 13}) || !reflect.DeepEqual(wall.DriverLink.LoadSources, []int{10}) {
		t.Fatalf("monthly arithmetic or original source ownership changed: %#v", wall)
	}
	// Reverse insertion order without changing immutable quantities/source lists.
	reversed := frames
	reversed.Cells = map[string]*epathSQLCell{}
	keys := []string{}
	for key := range frames.Cells {
		keys = append(keys, key)
	}
	for index := len(keys) - 1; index >= 0; index-- {
		reversed.Cells[keys[index]] = frames.Cells[keys[index]]
	}
	var again epathSQLModelChecks
	if err := epathSQLModelDriverLinkChecks(reversed, model, &again); err != nil {
		t.Fatal(err)
	}
	firstJSON, _ := json.Marshal(checks.Rows)
	secondJSON, _ := json.Marshal(again.Rows)
	if string(firstJSON) != string(secondJSON) {
		t.Fatal("map insertion changed independent endpoint checks")
	}
	after, _ := json.Marshal(frames)
	if string(before) != string(after) {
		t.Fatal("link compilation mutated independent frames")
	}
}

