func TestEnergyPathRealSQLDriverLinksMonthFirstTaxonomy(t *testing.T) {
	frames, model, _, _ := epathSQLDriverLinksFixture(t)
	frames.Cells = map[string]*epathSQLCell{}
	for month := 1; month <= 12; month++ {
		load, exchange := 0.0, 0.0
		if month == 1 {
			load, exchange = 100, 4
		}
		if month == 2 {
			load, exchange = 100, 6
		}
		frames.Loads[epathSQLKey("Office", "cooling", month)] = epathSQLQuantity{Value: load}
		for _, item := range []struct {
			category string
			value    float64
		}{{"surface.interzone", exchange}, {"surface.exterior_walls", load - exchange}} {
			key := epathSQLKey("Office", item.category, month)
			frames.Cells[key] = &epathSQLCell{Zone: "Office", Family: item.category, Category: item.category, Month: month, BuildingVisible: true, SourceIDs: []int{12, 13}, Allocated: map[string]epathSQLQuantity{"cooling": {Value: item.value}, "heating": {}}}
		}
	}
	var checks epathSQLModelChecks
	if err := epathSQLModelDriverLinkChecks(frames, model, &checks); err != nil {
		t.Fatal(err)
	}
	want := map[string]float64{"building/balance.storage_other": 4, "building/interzone.transfer": 6, "building/surface.exterior_walls": 190, "zone/surface.interzone": 10, "zone/surface.exterior_walls": 190}
	for _, check := range checks.Rows {
		if check.Item.Period != "annual" || check.DriverLink.Service != "cooling" || check.Item.Target.Field != "fromValue" || check.DriverLink.Category == "" {
			continue
		}
		key := check.Item.Scope + "/" + check.DriverLink.Category
		value, ok := want[key]
		if !ok || check.Quantity.Value != value {
			t.Fatalf("annual regrouped the completed monthly taxonomy: %s=%g", key, check.Quantity.Value)
		}
		delete(want, key)
	}
	if len(want) > 0 {
		t.Fatalf("missing month-first categories: %v", want)
	}
	for _, check := range checks.Rows {
		if strings.Contains(check.Want.Key, "surface.interzone") && check.Item.Scope == "building" {
			t.Fatal("Zone-only category leaked into Building selector")
		}
	}
}
