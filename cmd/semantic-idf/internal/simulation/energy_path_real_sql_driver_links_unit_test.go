		nodes, links := graph(period, "")
		result.Periods = append(result.Periods, EnergyPeriod{ID: period, Nodes: nodes, Links: links})
		nodes, links = graph(period, "Office")
		zone.Periods = append(zone.Periods, EnergyPeriod{ID: period, Nodes: nodes, Links: links})
